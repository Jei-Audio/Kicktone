juce::MemoryBlock sampleBytes(const pt::Sample& s) {
    juce::MemoryBlock m;const size_t n=s.left.size();
    m.setSize(n*2*sizeof(float));
    if(n){std::memcpy(m.getData(),s.left.data(),n*sizeof(float));std::memcpy(static_cast<char*>(m.getData())+n*sizeof(float),s.right.data(),n*sizeof(float));}
    return m;
}
std::shared_ptr<const pt::Sample> sampleFrom(const juce::var& data,double rate) {
    const auto* m=data.getBinaryData();
    if(!m || m->getSize()==0 || m->getSize()%(2*sizeof(float))!=0 || !(rate>=8000 && rate<=384000))return nullptr;
    auto s=std::make_shared<pt::Sample>();s->rate=rate;const size_t n=m->getSize()/(2*sizeof(float));
    s->left.resize(n);s->right.resize(n);
    std::memcpy(s->left.data(),m->getData(),n*sizeof(float));std::memcpy(s->right.data(),static_cast<const char*>(m->getData())+n*sizeof(float),n*sizeof(float));
    return s;
}
