"""Cross-build the Kicktone Windows VST3 on Linux with LLVM-MinGW.

Usage: python3 CrossBuild.py --compiler /path/llvm-mingw/bin/x86_64-w64-mingw32-clang++
                             --binarydata <dir containing BinaryData.h and BinaryData1.cpp>
The BinaryData folder is generated by any CMake configure+build of this project
(build/juce_binarydata_TailtoneLogo/JuceLibraryCode). Output:
  build-win/Kicktone.vst3/Contents/x86_64-win/Kicktone.vst3
"""
import subprocess, pathlib, concurrent.futures, sys, argparse, os
parser=argparse.ArgumentParser()
parser.add_argument('--compiler',required=True)
parser.add_argument('--binarydata',required=True)
parser.add_argument('--jobs',type=int,default=os.cpu_count() or 2)
parser.add_argument('--out',default=None)
args=parser.parse_args()
root=pathlib.Path(__file__).resolve().parents[1]; cxx=args.compiler
bd=pathlib.Path(args.binarydata).resolve()
work=pathlib.Path(args.out).resolve() if args.out else root/'build-win'
(work/'obj').mkdir(parents=True,exist_ok=True)
name='Kicktone'
modules=['juce_core','juce_events','juce_data_structures','juce_graphics','juce_gui_basics','juce_gui_extra',
         'juce_audio_basics','juce_audio_formats','juce_audio_devices','juce_audio_processors','juce_audio_utils','juce_dsp']
J=root/'ThirdParty/JUCE/modules'
sources=[root/'Source/PluginProcessor.cpp',root/'Source/PluginEditor.cpp',bd/'BinaryData1.cpp']
sources+=[J/m/f'{m}.cpp' for m in modules]
sources+=[J/'juce_audio_processors/juce_audio_processors_ara.cpp',J/'juce_audio_processors/juce_audio_processors_lv2_libs.cpp',
          J/'juce_audio_plugin_client/juce_audio_plugin_client_VST3.cpp']
flags=['-std=c++17','-O2','-DNDEBUG','-DNOMINMAX','-D_WIN32_WINNT=0x0A00','-DWINVER=0x0A00','-DUNICODE','-D_UNICODE',
       '-municode','-mavx','-ffunction-sections','-fdata-sections',
       '-I'+str(J),'-I'+str(bd),'-I'+str(root/'ThirdParty/r8brain'),
       '-I'+str(J/'juce_audio_processors/format_types/VST3_SDK'),
       '-include',str(root/'scripts/PluginConfig.h'),'-w']
flags=[f for f in flags if f!='-mavx']   # keep the plain x86-64 baseline for every CPU
def compile(s):
    out=work/'obj'/(s.parent.name+'_'+s.stem+'.o')
    stable="/Source/" not in str(s)
    if stable and out.exists() and out.stat().st_mtime>s.stat().st_mtime:return out
    p=subprocess.run([cxx,*flags,'-c',str(s),'-o',str(out)],stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True)
    print(s.name,'OK' if p.returncode==0 else 'FAILED',p.stdout[-6000:] if p.returncode else '',flush=True)
    return out if p.returncode==0 else None
with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool: objs=list(pool.map(compile,sources))
if not all(objs):sys.exit(1)
libs=['winmm','gdi32','user32','kernel32','comdlg32','advapi32','shell32','ole32','oleaut32','uuid','ws2_32','wininet','version',
      'shlwapi','imm32','comctl32','dwmapi','dwrite','d2d1','dxgi','d3d11','dcomp','dxguid','dbghelp','ksuser','vfw32','bcrypt',
      'setupapi','rpcrt4','opengl32','crypt32','shcore','mfplat','mfuuid']
dll=work/f'{name}.vst3'/'Contents'/'x86_64-win'/f'{name}.vst3'
dll.parent.mkdir(parents=True,exist_ok=True)
subprocess.run([cxx,'-shared','-static','-municode','-Wl,--gc-sections','-s','-o',str(dll),*[str(o) for o in objs],*['-l'+l for l in libs]],check=True)
print('BUILT',dll)
