// v0.5.20 EQ POSITION. post = weight of the position after the distortion (0..1,
// 10 ms ramps on a switch). Settled positions are exact: post 0 = the EQ output
// (the old path), post 1 = the untouched input. The EQ always runs on the
// signal so its filter state is warm when the position changes.
void eqBeforeDistortion(tt::ParametricEQ& eq,float& l,float& r,float post) {
    if(post<=0.f){eq.process(l,r);return;}
    float el=l,er=r;eq.process(el,er);
    if(post>=1.f)return;
    const float w=1.f-post;l+=w*(el-l);r+=w*(er-r);
}
float eqAfterBlend(float input,float equalised,float post) {
    return post<=0.f?input:post>=1.f?equalised:input+post*(equalised-input);
}
