// v0.5.23 STRETCHED GLIDE: move a stretched legato slide onto the prepared note
// nearest the heard pitch (audio thread: no allocation or locks; one bounded phase
// search per step). Notes not prepared yet are skipped: the note being read keeps
// supplying the pitch through its read rate, as the classic slide does.
void PunchTailProcessor::advanceStretchedGlide(PlayingVoice& v) {
    const auto ready=[&](int n) {
        if(v.compositeTail)return v.tailWetPitches && v.tailWetPitches->hasNote(n) && v.tailWetPitches->notes[size_t(n)]!=nullptr;
        return v.pitches && v.pitches->hasNote(n);
    };
    int want=v.stretchedStepNote();
    while(want!=v.note && !ready(want))want+=want<v.note?1:-1;
    if(want==v.note)return;
    const double scale=v.pitches?v.pitches->stretchForNote(want)/v.pitches->stretchForNote(v.note):1.0;
    v.stepStretchedGlide(want);
    v.alignStretchedStep(v.previousPlaybackTail(),v.playbackTail(),v.nextTimelineOffset(scale));
}
void PunchTailProcessor::midi(const juce::MidiMessage& m) {
    if (m.isAllSoundOff() || m.isAllNotesOff()) { heldKeys.fill(false); masterEnvelope.noteOff(); return; }
    if (m.isNoteOff()) { heldKeys[size_t(m.getNoteNumber()&127)]=false; for(auto& v:voices) if(v.active && v.key==m.getNoteNumber() && v.channel==m.getChannel() && v.settings.gate) masterEnvelope.noteOff(); return; }
    if (!m.isNoteOn()) return;
    // v0.4.49 legato glide: a key pressed while another key is still held
    // slides the playing tail to the new note instead of retriggering.
    {
        const int pressed=m.getNoteNumber()&127;
        bool legato=false;
        for(int k=0;k<128;++k)if(k!=pressed&&heldKeys[size_t(k)]){legato=true;break;}
        heldKeys[size_t(pressed)]=true;
        if(legato && params.getRawParameterValue("glide")->load()>.5f) {
            PlayingVoice* playing=nullptr;
            for(auto& v:voices)if(v.active && v.release<0){playing=&v;break;}
            if(playing && playing->pitches) {
                const bool lowLane=params.getRawParameterValue("lowKeyPunch")->load()>.5f;
                const int target=pt::tailNoteForKey(pressed,lowLane);
                markPlayed(target);   // v0.5.15: prepared first from now on (and saved with the project)
                const double seconds=params.getRawParameterValue("glideTime")->load()*.001;
                // v0.5.23 stretched slide (always, v0.5.25): it passes through every note in
                // between, so they are prepared first too. Steps happen per sample in processBlock.
                for(int n=(std::min)(playing->note,target);n<=(std::max)(playing->note,target);++n)markPlayed(n);
                playing->glideToStretched(target,seconds);
                playing->key=pressed;playing->channel=m.getChannel();
                return; // no new punch, no envelope/reverb reset
            }
        }
    }
    // Select a free slot before choking the former note. Old immutable banks
    // remain worker-owned; no source destruction occurs on the audio thread.
    auto* chosen=&voices[nextVoice];nextVoice=(nextVoice+1)%voices.size();
    for(auto& v:voices)v.active=false; // mandatory monophonic kick choke
    wetOwner=int(chosen-voices.data());wetOwnerElapsedSeconds=0;wetOwnerPunchEndSeconds=0;wetResetPending=true;
    // v0.4.48: keys play one octave lower internally; D2..C#3 can use the low
    // punch lane (tail as the key above, Resampled punch an octave below).
    const int key=m.getNoteNumber();
    const bool lowLane=params.getRawParameterValue("lowKeyPunch")->load()>.5f;
    const int note=pt::tailNoteForKey(key,lowLane);
    const int punchIndex=pt::punchIndexForKey(key,lowLane);
    markPlayed(note);   // v0.5.15: lock-free; the worker renders played keys first
    auto s=settings(); s.root=note; // samples in the bank are already pitched, at unchanged duration
    chosen->punch=audioPunch;
    s.punchTimeScale=chosen->punch?chosen->punch->forNote(punchIndex).punchTimeScale:1.;
    chosen->reverb=audioReverb;
    chosen->pitches=audioBank;
    chosen->tailWetPitches=audioTailWetBank;
    const auto tailWetSettings=tailReverbSettings();
    s.trimMs *= chosen->pitches ? chosen->pitches->stretchForNote(note) : 1.0;
    s.tailEndTrimMs *= chosen->pitches ? chosen->pitches->stretchForNote(note) : 1.0; // same scaling as the start trim
    // v0.5.15: a partial composite is used only for its final notes; a note
    // still being prepared plays the dry tail, as while preparing before.
    const bool compositeReady=compositeUsable(chosen->tailWetPitches.get(),chosen->pitches.get()) && chosen->tailWetPitches->hasNote(note);
    const pt::Sample* selectedTail=nullptr;
    bool preparedComposite=false;
    double compositeDryDuration=0;
    if(compositeReady) {
        selectedTail=chosen->tailWetPitches->notes[size_t(note)].get();
        compositeDryDuration=chosen->tailWetPitches->dryTailDurations[size_t(note)];
        preparedComposite=selectedTail!=nullptr;
    } else {
        selectedTail=chosen->pitches?&chosen->pitches->notes[size_t(note)]:nullptr;
    }
    chosen->start(note,m.getChannel(),m.getFloatVelocity(),chosen->punch?&chosen->punch->forNote(punchIndex).sample:nullptr,
                  selectedTail,s,
                  chosen->reverb?&chosen->reverb->sample:nullptr,
                  0.0,tailWetSettings.tailOffsetMs,preparedComposite,compositeDryDuration);
    chosen->key=key;chosen->punchIndex=punchIndex;
    chosen->crunch=(audioCrunch && audioCrunch->dry==chosen->pitches &&
                    (preparedComposite ? audioCrunch->wet==chosen->tailWetPitches : true)) ? audioCrunch : nullptr;
    const std::array<bool,3> muted{{params.getRawParameterValue("mutePunch")->load()>.5f,
        params.getRawParameterValue("muteTail")->load()>.5f,params.getRawParameterValue("muteReverb")->load()>.5f}};
    const double duration=tt::completeOutputDuration(*chosen,bool(chosen->punch),selectedTail!=nullptr,
        tailWetSettings,punchReverbSettings(),muted);
    masterEnvelope.start(rate,duration,masterEnvelopeSettings());
    chosen->regionEQ.start(punchRegionDesign,rate,chosen->punchEnd);
    // Immutable worker-prepared note map; no correlation scanning or new
    // allocations on the realtime note-on path. Ignore stale maps.
    if(audioPhase && audioPhase->automatic==(params.getRawParameterValue("phaseAuto")->load()>0.5f) &&
       audioPhase->matches(s, chosen->punch.get(),chosen->pitches.get(),note) &&
       audioPhase->composite.get()==(preparedComposite?chosen->tailWetPitches.get():nullptr)) {
        const auto& solution=audioPhase->notes[size_t(punchIndex)];
        if(solution.valid) {
            if(audioPhase->automatic)chosen->settings.phaseShiftMs+=solution.offsetMs;
            chosen->settings.joinCorrelation=audioPhase->automatic?solution.after:solution.before;
        }
    }
    chosen->setReverbFilter(selectedHPF(),rate,true);
}
