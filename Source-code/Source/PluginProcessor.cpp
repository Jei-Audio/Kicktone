uint64_t PunchTailProcessor::tailContentKey(const std::shared_ptr<const Asset>& tail) {
    if(hashedTail==tail)return hashedTailValue;
    KeyHash k;k.add(tail->sample.rate).add(int(tail->sample.left.size()));
    for(const auto* channel:{&tail->sample.left,&tail->sample.right})
        for(float v:*channel){uint32_t u;std::memcpy(&u,&v,4);k.h^=u;k.h*=1099511628211ull;}
    hashedTail=tail;hashedTailValue=k.h;return k.h;
}

std::shared_ptr<PunchTailProcessor::CrunchBank> PunchTailProcessor::crunchFor(const std::shared_ptr<const CrunchBank>& previous,
        const std::shared_ptr<const Bank>& dry,const std::shared_ptr<const TailWetBank>& wet,const std::function<bool()>& stale,bool& aborted,bool announce) {
    aborted=false;
    if(!dry)return nullptr;
    const int character=crunchCharacterValue();const double lowCut=crunchLowCutValue();const bool lostOnly=crunchLostOnlyValue();
    const auto ch=pt::crunchmatch::Character(std::clamp(character,0,2));
    auto next=std::make_shared<CrunchBank>();
    next->dry=dry;next->wet=wet;next->character=character;next->lowCutHz=lowCut;next->lostOnly=lostOnly;
    const bool sameSettings=previous && previous->character==character && std::abs(previous->lowCutHz-lowCut)<.5 && previous->lostOnly==lostOnly;
    const bool reuseDry=sameSettings && previous->dry && dry->key!=0 && previous->dry->key==dry->key;
    const bool reuseWet=sameSettings && previous->wet && wet && wet->key!=0 && previous->wet->key==wet->key;
    if(announce)setStatus(lostOnly?"Crunch (lost only): preparing layers...":"Crunch: preparing layers...");
    const int root=juce::jlimit(0,127,int(std::lround(dry->root)));
    // Notes outside the pitched range (and the root) hold the unshifted tail.
    // v0.5.15: a pitched note gets its layer once its tail note is final;
    // layers of notes already final in the previous bank (same content key)
    // are reused - each layer is a pure function of its note and the root.
    const auto build=[&](const auto& note,const auto& has,const pt::Sample& rootNote,auto& layers,bool shared,
                         bool reuse,const CrunchBank::Side* previousSide,const std::array<std::shared_ptr<const pt::Sample>,128>* previousLayers,
                         CrunchBank::Side& side) {
        if(reuse && previousSide && previousSide->valid)side=*previousSide;
        else {
            auto rootLayer=pt::crunchmatch::rootLayer(rootNote,ch,lowCut);
            side.target=rootLayer.mixedDb;side.rootOwn=pt::crunchmatch::brightnessDb(rootNote);
            side.rootEnergy=pt::crunchmatch::energy(rootLayer.audio); // v0.4.60 level match for higher notes
            // v0.5.7 LOST ONLY: the root (and every unshifted / pitched-up note) gets a silent layer.
            side.rootLayer=std::make_shared<const pt::Sample>(lostOnly?pt::crunchmatch::lost::silentLike(rootNote):std::move(rootLayer.audio));
            const auto edges=pt::crunchmatch::lost::bandEdges(lowCut,rootNote.rate);
            side.rootPower=lostOnly?pt::crunchmatch::lost::bandPower(rootNote,edges):std::vector<double>{};
            side.valid=true;
        }
        const auto edges=pt::crunchmatch::lost::bandEdges(lowCut,rootNote.rate);
        // v0.4.65: the matched layers are independent per source, so the
        // distinct sources are rendered in parallel (same matchedLayer call,
        // bit-identical per note); shared sources are still rendered once.
        struct Job { int firstNote; const pt::Sample* src; std::vector<int> notes; };
        std::vector<Job> jobs;
        for(int n=0;n<128;++n) {
            const pt::Sample* src=note(n);
            if(!src || src->left.empty())continue;
            const bool unshifted=n==root || n<pt::kLowestPitchNote || n>pt::kHighestPitchNote;
            if(unshifted || (lostOnly && n>root)){layers[size_t(n)]=side.rootLayer;next->drives[size_t(n)]=pt::crunchmatch::kRootDrive;continue;}
            if(!has(n))continue;   // not final yet: a later batch adds its layer
            if(reuse && previousLayers && (*previousLayers)[size_t(n)]) {
                layers[size_t(n)]=(*previousLayers)[size_t(n)];if(!shared)next->drives[size_t(n)]=previous->drives[size_t(n)];continue;
            }
            if(shared){bool reused=false;for(auto& j:jobs)if(j.src==src){j.notes.push_back(n);reused=true;break;}if(reused)continue;}
            jobs.push_back({n,src,{n}});
        }
        if(stale())return false;
        std::atomic<bool> abort{false};
        std::vector<std::shared_ptr<const pt::Sample>> results(jobs.size());
        std::vector<double> drives(jobs.size(),0.0);
        pt::parallel::forEach(jobs.size(),[&](size_t i) {
            if(abort.load())return;
            if(stale()){abort.store(true);return;}
            if(lostOnly){
                auto filled=pt::crunchmatch::lost::layer(*jobs[i].src,side.rootPower,edges,ch,lowCut,side.rootOwn);
                drives[i]=filled.drive;
                results[i]=std::make_shared<const pt::Sample>(std::move(filled.audio));
            } else {
                auto matched=pt::crunchmatch::matchedLayer(*jobs[i].src,side.target,ch,lowCut,side.rootOwn,true,side.rootEnergy);
                drives[i]=matched.drive;
                results[i]=std::make_shared<const pt::Sample>(std::move(matched.audio));
            }
        });
        if(abort.load() || stale())return false;
        for(size_t i=0;i<jobs.size();++i)
            for(int n:jobs[i].notes){layers[size_t(n)]=results[i];if(!shared)next->drives[size_t(n)]=drives[i];}
        return true;
    };
    try {
        if(!build([&](int n){return &dry->notes[size_t(n)];},[&](int n){return dry->hasNote(n);},dry->notes[size_t(root)],next->dryLayers,false,
                  reuseDry,previous?&previous->drySide:nullptr,previous?&previous->dryLayers:nullptr,next->drySide)){aborted=true;return nullptr;}
        if(wet && wet->notes[size_t(root)] &&
           !build([&](int n){return wet->notes[size_t(n)].get();},[&](int n){return wet->hasNote(n);},*wet->notes[size_t(root)],next->wetLayers,true,
                  reuseWet,previous?&previous->wetSide:nullptr,previous?&previous->wetLayers:nullptr,next->wetSide)){aborted=true;return nullptr;}
    } catch(const std::exception& e) { setStatus("Crunch failed: "+juce::String(e.what()));aborted=true;return nullptr; }
    return next;
}

std::shared_ptr<PunchTailProcessor::PhaseMap> PunchTailProcessor::phaseFor(const std::shared_ptr<const PhaseMap>& previous,const std::shared_ptr<const Asset>& punch,
        const std::shared_ptr<const Bank>& pitches,const std::shared_ptr<const TailWetBank>& composite,const std::function<bool()>& stale) {
    if(!punch || !pitches)return nullptr;
    auto s=settings();
    const bool automatic=params.getRawParameterValue("phaseAuto")->load()>0.5f;
    s.punchTimeScale=punch->punchTimeScale;s.trimMs*=pitches->stretch;
    auto next=std::make_shared<PhaseMap>();
    next->punch=punch;next->pitches=pitches;next->composite=composite;
    next->trimMs=s.trimMs;
    next->punchEndOffsetMs=s.punchEndOffsetMs;
    next->joinMs=s.joinMs;next->crossfadeMs=s.crossfadeMs;
    next->manualMs=s.phaseShiftMs;next->invert=s.invertTail;next->invertPunch=s.invertPunch;next->automatic=automatic;
    // v0.5.15: indices whose tail note was already final with the same content
    // key, punch and settings keep their analysis (a pure function of both).
    const bool reuse=previous && previous->automatic==automatic && previous->sameSettings(s,punch.get()) &&
        previous->pitches && pitches->key!=0 && previous->pitches->key==pitches->key &&
        ((!previous->composite && !composite) || (previous->composite && composite && composite->key!=0 && previous->composite->key==composite->key));
    for(int n=0;n<pt::kPunchIndexCount;++n) {
        if(stale())return nullptr;
        const int tailNote=pt::tailNoteForPunchIndex(n);
        if(composite ? !composite->hasNote(tailNote) : !pitches->hasNote(tailNote))continue;   // not final yet
        if(reuse && previous->done[size_t(n)]){next->notes[size_t(n)]=previous->notes[size_t(n)];next->done.set(size_t(n));continue;}
        auto ns=s;
        ns.root=tailNote;ns.trimMs=next->trimMs*pitches->stretchForNote(tailNote)/pitches->stretch;
        ns.punchTimeScale=punch->forNote(n).punchTimeScale;
        const pt::Sample* played=&pitches->notes[size_t(tailNote)];
        if(composite && composite->notes[size_t(tailNote)]) {
            // The composite is already trimmed and plays from its start.
            played=composite->notes[size_t(tailNote)].get();ns.trimMs=0;
        }
        next->notes[size_t(n)]=pt::phase::analyse(&punch->forNote(n).sample,played,ns,tailNote,automatic);
        next->done.set(size_t(n));
    }
    return next;
}

bool PunchTailProcessor::prepareTailBanks(pt::TailCompositeCache& compositeCache) {
    auto tail=asset(1);
    const double root=settings().root, stretch=stretchValue(); const int quality=qualityValue();
    const bool crunch=crunchValue();
    const double adaptive=quality==3?params.getRawParameterValue("adaptiveAmount")->load():0.;
    const auto adaptiveValue=[&] {return qualityValue()==3?double(params.getRawParameterValue("adaptiveAmount")->load()):0.;};
    const auto formantValue=[&] {return 0.;};
    const double formant=formantValue();
    const auto drop=pitchDropSettings(1);
    const double dropOnset=drop.active()?settings().trimMs*stretch*.001:0.;
    const auto dropStale=[&] {return pitchDropSettings(1)!=drop || (drop.active() && std::abs(settings().trimMs*stretch*.001-dropOnset)>1.e-9);};
    const auto wetSettings=tailReverbSettings();
    const double trim=settings().trimMs;
    const auto wetBands=eqSettings(3);
    const bool wetEQOn=params.getRawParameterValue("tailVerbEqOn")->load()>.5f;
    const bool wetLinear=tailWetUsesLinearPhase(),wetMono=tailWetUsesSubMono();
    const double wetMonoHz=tailWetSubMonoHz();
    const double endTrim=tailEndTrimValue(),endFade=tailEndFadeValue();
    pt::TailCompositeRenderSettings wetProcessing{wetBands,wetEQOn,wetLinear,wetMono,adaptive,formant,wetMonoHz,endTrim,endFade};
    wetProcessing.drop=drop;
    const bool wetOn=wetSettings.tailRootPitch && wetSettings.enabled && wetSettings.tailSend && wetSettings.mix>0.f;
    if(!wetOn) {
        failedWetKey=0;
        const juce::ScopedLock l(assetLock);
        if(tailWetBank){retiredTailWetBanks.push_back(tailWetBank);tailWetBank.reset();}
    }
    using pt::progress::Phase;
    if(!tail){progress.setReady(0,pt::kPitchNoteCount);progress.setPhase(Phase::NoTail);return false;}
    // Settings-only keys gate a re-render until the knob settles (v0.5.10);
    // the content keys also include the tail audio and the version.
    KeyHash dryGateKey;dryGateKey.add(root).add(stretch).add(quality).add(crunch).add(adaptive).add(formant).add(dropOnset)
        .add(drop.active()).add(drop.enabled).add(drop.amount).add(drop.timeMs).add(drop.curve).add(drop.target);
    KeyHash dk=dryGateKey;dk.addU64(tailContentKey(tail)).addU64(renderKey());   // v0.5.16: render key, not the version
    KeyHash wetGateKey;wetGateKey.add(trim).add(root).add(stretch).add(quality).add(crunch).add(adaptive).add(formant)
        .add(wetSettings.spaceMs).add(wetSettings.width).add(wetSettings.distance).add(wetSettings.mix).add(wetSettings.levelDb)
        .add(wetSettings.duckAmount).add(wetSettings.duckHz).add(wetSettings.duckRecovery).add(wetSettings.tailOffsetMs).add(wetSettings.tailFadeMs)
        .add(wetSettings.engine).add(wetSettings.wetAutoMatch).add(wetSettings.wetPhaseLock).add(wetSettings.keepDry).add(wetSettings.tailSend)
        .add(wetEQOn).add(wetLinear).add(wetMono).add(wetMonoHz).add(endTrim).add(endFade);
    for(const auto& b:wetBands)wetGateKey.add(b.enabled).add(b.type).add(b.slope).add(b.hz).add(b.gain).add(b.q);
    KeyHash wk=wetGateKey;wk.addU64(dk.h);
    std::shared_ptr<Bank> currentDry;std::shared_ptr<TailWetBank> currentWet;
    std::shared_ptr<const CrunchBank> currentCrunch;std::shared_ptr<PhaseMap> currentPhase;std::shared_ptr<const ProjectCache> saved;
    {const juce::ScopedLock l(assetLock);currentDry=bank;currentWet=tailWetBank;currentCrunch=crunchBank;currentPhase=phaseMap;saved=pendingCache;}
    // A complete bank published without a content key (a test fixture or an
    // older code path) is kept when it was made with the same settings, as before.
    const bool keylessMatch=currentDry && currentDry->key==0 && currentDry->prepared && std::abs(currentDry->root-root)<0.0001 &&
       std::abs(currentDry->requestedStretch-stretch)<0.00001 && currentDry->quality==quality && currentDry->crunch==crunch &&
       currentDry->adaptiveAmount==adaptive && currentDry->formant==formant && currentDry->drop==drop && currentDry->dropOnset==dropOnset;
    const bool dryFresh=!keylessMatch && (!currentDry || currentDry->key!=dk.h || !currentDry->usable());
    // v0.5.19 progress bar: expected render cost of the missing keys (learned per
    // key, see PreparationProgress.h), batch by batch in the order rendered below:
    // played keys, then perBatch at a time nearest the root, on renderThreads threads.
    const unsigned renderThreads=(std::max)(1u,pt::parallel::threads());
    const size_t perBatch=(std::max)(size_t(4),size_t(renderThreads)*size_t(quality==5?2:6));
    const auto keyWeight=[&](int n){return progress.weightFor(n-root);};
    const auto costOf=[&](const std::vector<int>& keys) {
        std::vector<double> w;w.reserve(keys.size());
        for(int n:keys)w.push_back(keyWeight(n));
        return pt::progress::batchCost(w.data(),w.size(),renderThreads);
    };
    const auto remainingCost=[&](const std::vector<int>& keys) {
        std::vector<int> played,rest;
        for(int n:keys)(wasPlayed(n)?played:rest).push_back(n);
        double cost=played.empty()?0.0:costOf(played);
        rest=byDistanceFrom(rest,root);
        for(size_t i=0;i<rest.size();i+=perBatch)
            cost+=costOf(std::vector<int>(rest.begin()+std::ptrdiff_t(i),rest.begin()+std::ptrdiff_t((std::min)(rest.size(),i+perBatch))));
        return cost;
    };
    const double allCost=[&] {
        std::vector<int> all;
        for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)if(std::abs(n-root)>=1.e-5)all.push_back(n);
        return remainingCost(all);
    }();
    if(dryFresh)progress.setReady(0,pt::kPitchNoteCount,allCost);   // the old keys are about to be replaced
    if(dryFresh && !dryGate.ready(dryGateKey.h)){renderGated=true;progress.setPhase(Phase::Settling);return true;}
    bool wantWet=wetOn && failedWetKey.load()!=wk.h;
    bool wetWaiting=false;
    bool wetFresh=wantWet && (!currentWet || currentWet->key!=wk.h || !currentWet->usable());
    if(wetFresh)progress.setReady(0,pt::kPitchNoteCount,allCost);
    if(wetFresh && !wetGate.ready(wetGateKey.h)){renderGated=true;wantWet=false;wetFresh=false;wetWaiting=true;}
    {   // v0.5.19 progress bar: the speed is measured per engine configuration, per unit of tail length
        KeyHash rate;rate.add(quality).add(wantWet||wetWaiting).add(params.getRawParameterValue("crunchMix")->load()>0.f).add(int(pt::parallel::threads()));
        progress.setConfig(rate.h,tail->sample.duration()*stretch);
    }
    const auto requestPending=[&]{const juce::ScopedLock lock(requestLock);return requests[1].pending;};
    const auto drySettingsStale=[&] {
        if(threadShouldExit())return true;
        if(std::abs(settings().root-root)>.0001 || std::abs(stretchValue()-stretch)>.00001 || qualityValue()!=quality || crunchValue()!=crunch ||
           adaptiveValue()!=adaptive || formantValue()!=formant || dropStale())return true;
        if(requestPending())return true;
        const juce::ScopedLock lock(assetLock);return assets[1].get()!=tail.get();
    };
    const auto wetSettingsStale=[&] {
        const auto current=tailReverbSettings();
        const auto currentBands=eqSettings(3);
        bool bandsChanged=false;
        for(int i=0;i<tt::kBands;++i) {
            const auto& a=currentBands[size_t(i)];const auto& b=wetBands[size_t(i)];
            bandsChanged|=a.enabled!=b.enabled||a.type!=b.type||a.slope!=b.slope||a.hz!=b.hz||a.gain!=b.gain||a.q!=b.q;
        }
        return !current.tailRootPitch || !current.enabled || !current.tailSend || current.mix<=0.f ||
           std::abs(settings().trimMs-trim)>.001 || std::abs(current.mix-wetSettings.mix)>.01 ||
           std::abs(current.levelDb-wetSettings.levelDb)>.01 || std::abs(current.spaceMs-wetSettings.spaceMs)>.01 ||
           std::abs(current.width-wetSettings.width)>.01 || std::abs(current.distance-wetSettings.distance)>.01 ||
           std::abs(current.duckAmount-wetSettings.duckAmount)>.01 || std::abs(current.duckHz-wetSettings.duckHz)>.01 ||
           std::abs(current.duckRecovery-wetSettings.duckRecovery)>.01 || std::abs(current.tailOffsetMs-wetSettings.tailOffsetMs)>.01 || std::abs(current.tailFadeMs-wetSettings.tailFadeMs)>.01 || current.engine!=wetSettings.engine || current.wetAutoMatch!=wetSettings.wetAutoMatch || current.wetPhaseLock!=wetSettings.wetPhaseLock ||
           current.keepDry!=wetSettings.keepDry || (params.getRawParameterValue("tailVerbEqOn")->load()>.5f)!=wetEQOn ||
           tailWetUsesLinearPhase()!=wetLinear || tailWetUsesSubMono()!=wetMono || (wetMono && std::abs(tailWetSubMonoHz()-wetMonoHz)>.01) ||
           !pt::sameTailEnd(tailEndTrimValue(),tailEndFadeValue(),endTrim,endFade) || bandsChanged;
    };
    const auto workerId=std::this_thread::get_id();
    std::atomic<bool> stop{false};
    const auto stale=[&] {   // as v0.5.14: the worker thread keeps the linear-phase EQ responsive
        if(std::this_thread::get_id()==workerId)rebuildLinearEQ();
        if(stop.load())return true;
        if(drySettingsStale() || (wantWet && wetSettingsStale())){stop.store(true);return true;}
        return false;
    };
    const juce::String engine=engineName(quality);
    // v0.5.16: the dry engine (analysis + 4x/8x preparation) and the Root Render
    // setup are prepared only when a key must actually be rendered. A project
    // reopened with its played keys and base notes saved needs neither: the
    // fresh banks are built from the saved notes and published at once, and the
    // setup follows with the first missing key (a background batch or a newly
    // played key). Every rendered note is the same call as before.
    std::shared_ptr<Bank> nextDry;
    juce::String firstError;
    const bool savedDry=saved && saved->dryKey==dk.h;
    const bool baseNeedsEngine=std::abs(stretch-1.0)>0.00001 || drop.active();   // the unshifted note is a render
    const auto engineReady=[&]{return dryEngine && dryEngine->key==dk.h && dryEngine->source==tail;};
    // A fresh bank: the dry tail on every key, final outside 15..51 and on the root.
    const auto makeFresh=[&] {
        auto fresh=std::make_shared<Bank>();
        fresh->drop=drop;fresh->dropOnset=dropOnset;fresh->root=root;fresh->stretch=stretch;fresh->requestedStretch=stretch;
        fresh->quality=quality;fresh->adaptiveAmount=adaptive;fresh->formant=formant;fresh->crunch=crunch;fresh->key=dk.h;
        pt::fillDryPitchBank(fresh->notes,tail->sample);
        return fresh;
    };
    const auto markBaseReal=[&](Bank& b){for(int n=0;n<128;++n)if(n<pt::kLowestPitchNote || n>pt::kHighestPitchNote || std::abs(n-root)<1.e-5)b.real.set(size_t(n));};
    // As before: a failed engine leaves every pitched note on the dry tail.
    const auto failBank=[&](Bank& b){b.fallback=pt::kPitchNoteCount;b.stretch=1.0;b.real.set();};
    // Analysis + engine preparation; with `fresh`, also the unshifted base note.
    // false = cancelled (settings moved on: the next pass starts again).
    const auto prepareEngine=[&](Bank* fresh)->bool {
        auto engineState=std::make_shared<DryEngine>();engineState->key=dk.h;engineState->source=tail;
        ++enginePrepares;progress.setPhase(Phase::Setup);
        try {
            const double rootHz=440.0*std::pow(2.0,(root-69.0)/12.0);
            if(compositeCache.cycleSource==&tail->sample && compositeCache.cycleRoot==root)
                engineState->analysis=compositeCache.sourceAnalysis;
            else {
                engineState->analysis=pt::cycle::analyzeWithManualRoot(tail->sample,rootHz);
                compositeCache.cycleSource=&tail->sample;compositeCache.cycleRoot=root;
                compositeCache.sourceAnalysis=engineState->analysis;++compositeCache.analysisBuilds;
            }
            setStatus(engine+(quality==5?": preparing complete tail at 8x resolution...":": preparing complete tail at 4x resolution..."));
            if(quality==5)engineState->extreme=pt::extreme5::prepare(tail->sample,engineState->analysis,stretch,stale);
            else engineState->character=pt::character::prepare(tail->sample,engineState->analysis,stretch,stale);
            if(fresh && baseNeedsEngine) {
                auto unshifted=quality==5?pt::extreme5::render(tail->sample,0.0,engineState->extreme,stale)
                                         :pt::character::render(tail->sample,0.0,engineState->character,stale,nullptr,
                                              quality==3?stretch*pt::adaptiveDurationRatio(0.0,adaptive):0.);
                if(drop.active())unshifted=pt::drop::render(unshifted,drop,440.*std::pow(2.,(root-69.)/12.),dropOnset,stale);
                if(!pt::usablePitchResult(tail->sample,unshifted,stretch))
                    throw std::runtime_error("Stretch render was silent or invalid");
                pt::fillDryPitchBank(fresh->notes,unshifted);
            }
            engineState->ok=true;
        } catch(const std::exception& e) {
            if(stale())return false;
            engineState->error=juce::String(e.what());firstError=engineState->error;
        }
        dryEngine=engineState;
        return true;
    };
    if(dryFresh) {
        if(!claimPreparation(true,stale))return true;   // v0.5.16 shared preparation slots
        auto fresh=makeFresh();
        const bool savedBase=savedDry && saved->baseDry;
        const bool engineNow=baseNeedsEngine && !savedBase;
        if(engineNow && !prepareEngine(fresh.get()))return true;
        if(baseNeedsEngine && savedBase)pt::fillDryPitchBank(fresh->notes,*saved->baseDry);
        markBaseReal(*fresh);
        if(engineNow && !dryEngine->ok)failBank(*fresh);
        else if(savedDry) {   // prepared notes saved in the project
            for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)
                if(saved->dry[size_t(n)] && !fresh->real[size_t(n)]) {
                    fresh->notes[size_t(n)]=*saved->dry[size_t(n)];fresh->noteStretches[size_t(n)]=saved->noteStretch[size_t(n)];
                    fresh->real.set(size_t(n));++fresh->pitched;
                }
        }
        nextDry=fresh;
    }
    // ---- the Root Render composite: one-time setup (lazy, see above), then per-note renders
    std::shared_ptr<TailWetBank> nextWet;
    bool wetFailed=false;
    const auto wetReady=[&]{return wetPrep && wetPrepKey==wk.h;};
    const auto prepareWet=[&]()->bool {   // false = cancelled
        setStatus("Preparing one Tail + experimental reverb render for the selected pitch/stretch engine...");
        ++wetPrepares;progress.setPhase(Phase::Setup);
        try {
            const auto wetCancel=[&]{return stale();};
            wetPrep=std::make_shared<pt::RootTailCompositePrep>(pt::prepareRootTailComposite(tail->sample,root,trim,wetSettings,
                stretch,quality,crunch,wetProcessing,wetCancel,&compositeCache));
            wetPrepKey=wk.h;
        } catch(const std::exception& e) {
            if(stale())return false;
            wetPrep.reset();wetPrepKey=0;wetFailed=true;wantWet=false;wetFresh=false;
            failedWetKey=wk.h;setStatus("Tail + experimental reverb preparation failed: "+juce::String(e.what()));
        }
        return true;
    };
    const bool savedWetBase=saved && saved->wetKey==wk.h && saved->baseWet;
    if(wantWet && wetFresh && !savedWetBase && !wetReady()) {
        if(!claimPreparation(true,stale))return true;   // v0.5.16 shared preparation slots
        if(!prepareWet())return true;
    }
    if(wantWet && wetFresh) {
        nextWet=std::make_shared<TailWetBank>();auto& b=*nextWet;
        b.source=tail;b.root=root;b.stretch=stretch;b.trimMs=trim;
        b.formant=formant;b.quality=quality;b.crunch=crunch;b.spaceMs=wetSettings.spaceMs;b.width=wetSettings.width;b.distance=wetSettings.distance;
        b.mix=wetSettings.mix;b.levelDb=wetSettings.levelDb;b.duckAmount=wetSettings.duckAmount;
        b.duckHz=wetSettings.duckHz;b.duckRecovery=wetSettings.duckRecovery;b.tailOffsetMs=wetSettings.tailOffsetMs;b.tailFadeMs=wetSettings.tailFadeMs;b.engine=wetSettings.engine;b.autoMatch=wetSettings.wetAutoMatch;b.phaseLock=wetSettings.wetPhaseLock;
        b.adaptiveAmount=adaptive;b.wetBands=wetBands;b.enabled=wetSettings.enabled;b.keepDry=wetSettings.keepDry;
        b.tailSend=wetSettings.tailSend;b.wetEQ=wetEQOn;b.linearPhase=wetLinear;b.subMono=wetMono;b.subMonoHz=wetMonoHz;b.tailEndTrimMs=endTrim;b.tailEndFadeMs=endFade;
        if(wetReady()) {
            b.notes=wetPrep->base.notes;b.dryTailDurations=wetPrep->base.dryTailDurations;
            b.matchShiftMs=wetPrep->base.wetMatch.shift*1000.0/tail->sample.rate;b.matchPolarity=wetPrep->base.wetMatch.polarity;
        } else {   // v0.5.16: the base composite saved in the project (identical to prepareRootTailComposite's)
            b.notes.fill(saved->baseWet);b.dryTailDurations.fill(saved->baseWetDryTail);
            b.matchShiftMs=saved->matchShiftMs;b.matchPolarity=saved->matchPolarity;
        }
        b.key=wk.h;
        for(int n=0;n<128;++n)if(n<pt::kLowestPitchNote || n>pt::kHighestPitchNote || std::abs(n-root)<1.e-5)b.real.set(size_t(n));
        if(saved && saved->wetKey==wk.h)
            for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)
                if(saved->wet[size_t(n)] && !b.real[size_t(n)]) {
                    b.notes[size_t(n)]=saved->wet[size_t(n)];b.dryTailDurations[size_t(n)]=saved->dryTailDuration[size_t(n)];b.real.set(size_t(n));
                }
    }
    const Bank* dryView=nextDry?nextDry.get():currentDry.get();
    const TailWetBank* wetView=wantWet?(nextWet?nextWet.get():(currentWet && currentWet->key==wk.h?currentWet.get():nullptr)):nullptr;
    const auto dryMissing=[&](int n){return !dryView->hasNote(n);};
    const auto wetMissing=[&](int n){return wetView && !wetView->hasNote(n);};
    std::vector<int> missing;
    for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)if(dryMissing(n)||wetMissing(n))missing.push_back(n);
    if(!wetWaiting)progress.setReady(pt::kPitchNoteCount-int(missing.size()),pt::kPitchNoteCount,remainingCost(missing));   // v0.5.19 (a settling Root Render stays at 0)
    // ---- choose the batch: played keys first; otherwise a few of the rest
    std::vector<int> batch;
    for(int n:missing)if(wasPlayed(n))batch.push_back(n);
    const bool playedBatch=!batch.empty();
    const bool fresh=nextDry || nextWet;
    if(!playedBatch && !missing.empty() && !fresh) {
        batch=byDistanceFrom(missing,root);
        if(batch.size()>perBatch)batch.resize(perBatch);
    }
    if(batch.empty() && !fresh && !wetFailed) {   // nothing to do
        progress.setPhase(wetWaiting?Phase::Settling:missing.empty()?Phase::Ready:Phase::Rendering);
        return wetWaiting;
    }
    // v0.5.16: keys nobody played wait until no Tailtone instance has done
    // foreground preparation for a few seconds (project load, setting changes),
    // then take a free turn (never queued behind foreground work), one batch at a time.
    const bool foreground=playedBatch || fresh || wetFailed;
    if(!foreground) {   // foreground work earlier in this pass counts too (its turn is still held)
        const auto deferred=[&](int waitMs,bool turnsBusy) {
            backgroundDeferMs=waitMs;
            progress.setPhase(Phase::Paused,turnsBusy?0.0:waitMs*.001);
            if(turnsBusy)progress.setWaiting(true);
            int ready=0;for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)if(!dryMissing(n)&&!wetMissing(n))++ready;
            setStatus(engine+": "+juce::String(ready)+"/"+juce::String(pt::kPitchNoteCount)+
                " keys ready; the other keys follow after a few seconds without changes (Kicktone instances take turns to keep the CPU low).");
            return true;
        };
        if(const int waitMs=pt::parallel::preparationGate().backgroundWaitMs();waitMs>0)return deferred(waitMs,false);
        if(!prepSlot.claim(pt::parallel::Priority::Background))return deferred(50,true);   // every turn busy: look again shortly
    }
    if(!claimPreparation(foreground,stale))return true;
    // v0.5.16 lazy setup: prepare the engine / Root Render setup now that a key needs it.
    {
        bool needDry=false,needWet=false;
        for(int n:batch){needDry|=dryMissing(n);needWet|=wetMissing(n);}
        if(needDry && !engineReady()) {
            if(!prepareEngine(nullptr))return true;
            if(!dryEngine->ok) {   // as for a fresh bank: every pitched note keeps the dry tail
                nextDry=makeFresh();markBaseReal(*nextDry);failBank(*nextDry);dryView=nextDry.get();
            }
        }
        if(needWet && wantWet && !wetReady()) {
            if(!prepareWet())return true;
            if(wetFailed){nextWet.reset();wetView=nullptr;}
        }
    }
    // ---- render the batch (each note: dry tail, then its composite)
    struct Out { bool dryDone=false, dryFail=false, wetDone=false, wetFail=false; pt::Sample dry; pt::RootTailCompositeNote wet; juce::String error; };
    std::vector<Out> out(batch.size());
    const double batchCostUnits=costOf(batch);   // v0.5.19: each finished key reports its share
    std::vector<double> keyWeights;double batchWeight=0;
    for(int n:batch){keyWeights.push_back(keyWeight(n));batchWeight+=keyWeights.back();}
    // v0.5.19 progress bar: a batch counts as measured once it is published (crunch
    // layers and phase map included); any earlier return cancels it.
    struct BatchProgress {
        pt::progress::Tracker& t; bool open=false;
        void begin(int keys,double weight){t.beginBatch(keys,weight,progressNow());open=true;}
        void end(bool committed){if(open){open=false;t.endBatch(committed,progressNow());}}
        ~BatchProgress(){end(false);}
    } batchProgress{progress};
    if(!batch.empty()) {
        rebuilding=true;
        batchProgress.begin(int(batch.size()),batchCostUnits);
        int ready=0;for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)if(!dryMissing(n)&&!wetMissing(n))++ready;
        setStatus(playedBatch?engine+": preparing your played keys first ("+juce::String(int(batch.size()))+")...":
                              engine+": played keys ready; preparing the other keys in the background ("+juce::String(ready)+"/"+juce::String(pt::kPitchNoteCount)+")...");
        const auto renderDry=[&](double shift) {
            auto result=quality==5?pt::extreme5::render(tail->sample,shift,dryEngine->extreme,stale)
                                  :pt::character::render(tail->sample,shift,dryEngine->character,stale,nullptr,
                                       quality==3?stretch*pt::adaptiveDurationRatio(shift,adaptive):0.);
            if(drop.active())result=pt::drop::render(result,drop,440.*std::pow(2.,(root+shift-69.)/12.),dropOnset,stale);
            return result;
        };
        pt::parallel::forEach(batch.size(),[&](size_t i) {
            const int n=batch[i];
            if(stale())return;
            const double keyStart=progressNow();
            if(dryMissing(n)) {
                if(!dryEngine->ok){out[i].dryFail=true;out[i].error=dryEngine->error;}
                else try {
                    const double shift=n-root;
                    auto candidate=renderDry(shift);
                    if(stop.load())return;
                    if(!pt::usablePitchResult(tail->sample,candidate,quality==3?stretch*pt::adaptiveDurationRatio(shift,adaptive):stretch))
                        throw std::runtime_error("Rendered tail was empty, silent or invalid");
                    out[i].dry=std::move(candidate);out[i].dryDone=true;
                } catch(const std::exception& e) {
                    if(stop.load())return;   // a cancellation exception is not a note failure
                    out[i].dryFail=true;out[i].error=juce::String(e.what());
                }
            }
            if(wetMissing(n)) {
                try {
                    out[i].wet=pt::renderRootTailCompositeNote(*wetPrep,n,stale);out[i].wetDone=true;
                } catch(const std::exception& e) {
                    if(stop.load())return;
                    out[i].wetFail=true;if(out[i].error.isEmpty())out[i].error=juce::String(e.what());
                }
            }
            if(!stop.load()) {
                const double now=progressNow();
                progress.learnKey(n-root,now-keyStart);
                progress.keyDone(batchCostUnits*keyWeights[i]/batchWeight,now);
            }
        });
        rebuilding=false;
        if(stop.load() || stale())return true;
    }
    // ---- apply (copy-on-write: published objects stay immutable)
    for(size_t i=0;i<batch.size();++i) {
        const int n=batch[i];auto& o=out[i];
        if(o.dryDone || o.dryFail) {
            if(!nextDry)nextDry=std::make_shared<Bank>(*currentDry);
            if(o.dryDone) {
                nextDry->noteStretches[size_t(n)]=double(o.dry.left.size())/tail->sample.left.size();
                nextDry->notes[size_t(n)]=std::move(o.dry);++nextDry->pitched;
            } else {++nextDry->fallback;if(firstError.isEmpty())firstError=o.error;}
            nextDry->real.set(size_t(n));
        }
        if(o.wetFail){wetFailed=true;if(firstError.isEmpty())firstError=o.error;}
        if(o.wetDone && !wetFailed) {
            if(!nextWet)nextWet=std::make_shared<TailWetBank>(*currentWet);
            if(o.wet.rendered){nextWet->notes[size_t(n)]=o.wet.sample;nextWet->dryTailDurations[size_t(n)]=o.wet.dryTailDuration;}
            nextWet->real.set(size_t(n));
        }
    }
    if(wetFailed) {
        nextWet.reset();wantWet=false;failedWetKey=wk.h;
        setStatus("Tail + experimental reverb preparation failed: "+firstError);
    }
    if(nextDry){const bool done=nextDry->prepared || completeRange(nextDry->real);nextDry->prepared=done;nextDry->partial=!done;}
    const std::shared_ptr<const Bank> publishDry=nextDry?std::shared_ptr<const Bank>(nextDry):std::shared_ptr<const Bank>(currentDry);
    // A changed dry bank needs a composite bound to it (same notes, new pointer).
    if(wantWet && !nextWet && nextDry && currentWet && currentWet->key==wk.h && currentWet->usable())
        nextWet=std::make_shared<TailWetBank>(*currentWet);
    if(nextWet) {
        nextWet->dryBank=publishDry;
        const bool done=nextWet->prepared || completeRange(nextWet->real);nextWet->prepared=done;nextWet->partial=!done;
    }
    std::shared_ptr<const TailWetBank> publishWet=nextWet?std::shared_ptr<const TailWetBank>(nextWet):
        (wantWet && currentWet && currentWet->key==wk.h?std::shared_ptr<const TailWetBank>(currentWet):nullptr);
    std::shared_ptr<const TailWetBank> usableWet=publishWet && compositeUsable(publishWet.get(),publishDry.get())?publishWet:nullptr;
    // Crunch layers and the phase map for the same notes, published together.
    std::shared_ptr<CrunchBank> nextCrunch;
    if(params.getRawParameterValue("crunchMix")->load()>0.f) {
        bool aborted=false;
        nextCrunch=crunchFor(currentCrunch,publishDry,usableWet,stale,aborted,false);
        if(aborted)return true;
    }
    std::shared_ptr<const Asset> punch;
    {const juce::ScopedLock l(assetLock);punch=currentPunch();}
    auto nextPhase=phaseFor(currentPhase,punch,publishDry,usableWet,stale);
    if(stale())return true;
    {
        const juce::ScopedLock l(assetLock);
        if(assets[1].get()!=tail.get())return true;
        if(nextDry){if(bank)retiredBanks.push_back(bank);bank=nextDry;}
        if(wetFailed){if(tailWetBank){retiredTailWetBanks.push_back(tailWetBank);tailWetBank.reset();}}
        else if(nextWet){if(tailWetBank)retiredTailWetBanks.push_back(tailWetBank);tailWetBank=nextWet;}
        if(nextCrunch){if(crunchBank)retiredCrunch.push_back(crunchBank);crunchBank=std::move(nextCrunch);}
        if(nextPhase && currentPunch().get()==punch.get()){if(phaseMap)retiredPhaseMaps.push_back(phaseMap);phaseMap=std::move(nextPhase);}
        if(publishDry->prepared && (!wantWet || (publishWet && publishWet->prepared)))pendingCache.reset();   // restored notes are in use or obsolete
    }
    batchProgress.end(true);
    // ---- status
    const bool dryDone=publishDry->prepared, wetDone=!wantWet || (publishWet && publishWet->prepared);
    {   // v0.5.19 progress bar
        std::vector<int> left;for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)
            if(!publishDry->hasNote(n) || (wantWet && !(publishWet && publishWet->hasNote(n))))left.push_back(n);
        if(!wetWaiting)progress.setReady(pt::kPitchNoteCount-int(left.size()),pt::kPitchNoteCount,remainingCost(left));
        progress.setPhase(dryDone && wetDone?(wetWaiting?Phase::Settling:Phase::Ready):Phase::Rendering);
    }
    if(dryDone && wetDone) {
        if(wantWet && publishWet && nextWet && !wetFailed) {
            setStatus(juce::String("Tail + experimental reverb ready; each note uses one pitch/stretch render.")+
                (wetSettings.wetAutoMatch?" Auto match: "+juce::String(publishWet->matchShiftMs,2)+" ms"+(publishWet->matchPolarity<0?", inverted":""):juce::String())+
                (wetSettings.wetPhaseLock?" | Low phase lock ON":""));
        } else if(nextDry && !wetFailed) {
            if(publishDry->fallback>0) {
                setStatus(juce::String(engineName(publishDry->quality)) + ": " + juce::String(publishDry->pitched) +
                    " shifted notes ready on keys D#2-D#5; " +
                    juce::String(publishDry->fallback) + " failed (dry tail fallback). " +
                    (firstError.isNotEmpty()?"First issue: " + firstError :
                        "Other MIDI notes use the original tail."));
            } else setStatus(juce::String(engineName(publishDry->quality)) + " ready: keys D#2-D#5 | Tail stretch " + juce::String(publishDry->stretch*100.0,1) + "% | Outside range: unpitched tail");
        }
        return wetWaiting;
    }
    if(!wetFailed) {
        int ready=0;for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)
            if(publishDry->hasNote(n) && (!wantWet || (publishWet && publishWet->hasNote(n))))++ready;
        setStatus(engine+": played keys ready; preparing the other keys in the background ("+juce::String(ready)+"/"+juce::String(pt::kPitchNoteCount)+")...");
    }
    return true;
}

void PunchTailProcessor::rebuildPunch() {
    const auto original=asset(0);
    const auto drop=pitchDropSettings(0);
    const double pitch=params.getRawParameterValue("punchPitch")->load();
    const double root=settings().root;
    const int mode=punchPitchModeValue();
    // v0.5.10 PUNCH HARMONY: a harmony mode makes the punch follow every tail
    // key (as PUNCH FOLLOWS TAIL PITCH does) plus the interval for that key.
    const auto harmonyValue=[&]{return punchHarmonySettings();};
    const auto harmony=harmonyValue();
    const auto followValue=[&]{return params.getRawParameterValue("punchFollowTail")->load()>.5f || harmonyValue().mode!=pt::harmony::Off;};
    const auto punch2PitchValue=[&]{return double(params.getRawParameterValue("punch2Pitch")->load());};
    const bool follow=followValue();
    const auto decayOnlyValue=[&]{return params.getRawParameterValue("punchFollowDecayOnly")->load()>.5f;};
    const bool decayOnly=decayOnlyValue();
    const double punch2Pitch=punch2PitchValue();
    const auto layerValue=[&]()->std::shared_ptr<const Asset>{
        if(params.getRawParameterValue("punchLayer")->load()<=.5f)return {};
        return asset(3);
    };
    const auto layer=layerValue();
    // v0.4.50 decay layer settings: the Punch Attack/Decay split is where the
    // two punches meet; Punch 2 Offset shifts which part of Punch 2 is used.
    const auto layerSettings=[&]{
        struct L{double split,transition,offset,endMs;};
        return L{params.getRawParameterValue("punchRegionSplit")->load()*.01,
                 params.getRawParameterValue("punchRegionTransition")->load()*.001,
                 params.getRawParameterValue("punch2Offset")->load()*.001,
                 double(params.getRawParameterValue("punchOffset")->load()+params.getRawParameterValue("punchExtra")->load())};
    };
    const auto ls=layerSettings();
    // v0.5.5: split and Punch End also key the decay-note measurement, so they
    // count with or without a layer (a cheap re-measure, no DSP change).
    const auto sameLayer=[&](const decltype(ls)& x){
        if(std::abs(x.split-preparedLayerSplit)>1e-9||std::abs(x.endMs-preparedLayerEnd)>1e-9)return false;
        return !layer || (std::abs(x.transition-preparedLayerTransition)<1e-9&&
                          std::abs(x.offset-preparedLayerOffset)<1e-9&&
                          std::abs(punch2Pitch-preparedPunch2Pitch)<1e-9);
    };
    {
        const juce::ScopedLock lock(assetLock);
        if(!original || (preparedPunchSource==original && preparedPunchDrop==drop && preparedPunchLayer==layer && sameLayer(ls) && std::abs(preparedPunchPitch-pitch)<.0001 &&
           std::abs(preparedPunchRoot-root)<.0001 && preparedPunchMode==mode && preparedPunchFollow==follow && preparedPunchDecayOnly==decayOnly &&
           preparedPunchHarmony==harmony))return;
    }
    if(!claimPreparation(true,[&]{return threadShouldExit();}))return;   // v0.5.16 shared preparation slots
    const ActivityScope activity(progress,pt::progress::Activity::Punch);   // v0.5.19 progress bar
    // v0.4.50 punch layer = DECAY: Punch 1 plays up to the Attack/Decay split,
    // Punch 2 replaces it after the split (always trimmed: same timeline as
    // Punch 1, its own start before the split is not heard). The handover uses
    // the Attack/Decay Transition time. Punch 1's length is kept, so the punch
    // end, join and tail timing never move. Built here on the worker.
    const auto pitchMode=mode==2?pt::PunchPitchMode::HighestFidelity:mode==1?pt::PunchPitchMode::Resample:pt::PunchPitchMode::StretchAligned;
    // Punch 2 at Punch 1's sample rate (before any tuning).
    pt::Sample layerRaw;
    if(layer) {
        layerRaw=layer->sample;
        if(std::abs(layerRaw.rate-original->sample.rate)>1e-6) {
            layerRaw.left=pt::cycle::resample(layer->sample.left,layer->sample.rate,layer->sample.rate/original->sample.rate);
            layerRaw.right=pt::cycle::resample(layer->sample.right,layer->sample.rate,layer->sample.rate/original->sample.rate);
            layerRaw.rate=original->sample.rate;
        }
    }
    // Attack (Punch 1) + decay (Punch 2) mix. outScale / addScale = how much each
    // part's render changed its length (Resample mode); with both 1 this is exactly
    // the v0.4.50 mix. Times (Punch End trim, transition, offset) follow the attack.
    const auto mixLayer=[&](pt::Sample out,const pt::Sample& add,double outScale,double addScale) {
        const double rate=out.rate;
        const double audible=(std::max)(0.0,out.duration()-(std::max)(0.0,ls.endMs)*.001*outScale); // Punch End trim
        const double splitAt=std::clamp(ls.split,0.0,1.0)*audible;
        const double fade=(std::max)(ls.transition*outScale,1.0/rate);
        const bool sameScale=outScale==addScale;
        // v0.5.31: + moves Punch 2 RIGHT (heard later, earlier audio from the file),
        // - moves it left. Before v0.5.31 the sign was the other way round.
        const double offset=-ls.offset*rate*(sameScale?1.0:addScale);
        // Punch 2 enters at the source time where Punch 1 is at the split, then plays at its own rate.
        const double splitIndex=splitAt*rate, entry=sameScale?0.0:splitIndex*(addScale/outScale)-splitIndex;
        for(size_t i=0;i<out.left.size();++i){
            const double t=double(i)/rate;
            const double x=std::clamp((t-(splitAt-fade*.5))/fade,0.0,1.0);
            const double b=.5-.5*std::cos(pt::pi*x), a=1.0-b;   // constant-amplitude, like the region EQ
            if(b<=0)continue;
            const double pos=sameScale?double(i)+offset:double(i)+entry+offset;
            float l=0,r=0;
            if(pos>=0 && pos<double(add.left.size())){l=add.at(0,pos);r=add.at(1,pos);}
            out.left[i]=float(a*out.left[i]+b*l);out.right[i]=float(a*out.right[i]+b*r);
        }
        // Short fade if Punch 2 runs out before Punch 1 ends (no click).
        const double lastP2=double(add.left.size())-offset-(sameScale?0.0:entry);
        if(lastP2>0 && lastP2<double(out.left.size())) {
            const size_t f=size_t(std::ceil(.002*rate)),endIdx=size_t(lastP2);
            for(size_t k=0;k<f&&k<=endIdx;++k){
                const size_t i=endIdx-k;const float g=float(k)/float(f);
                const double t=double(i)/rate;const double x=std::clamp((t-(splitAt-fade*.5))/fade,0.0,1.0);
                if(x>=1.0){out.left[i]*=g;out.right[i]*=g;}
            }
        }
        return out;
    };
    // v0.4.50 punch layer = DECAY: Punch 1 plays up to the Attack/Decay split,
    // Punch 2 replaces it after the split (always trimmed: same timeline as
    // Punch 1, its own start before the split is not heard). The handover uses
    // the Attack/Decay Transition time. Punch 1's length is kept, so the punch
    // end, join and tail timing never move. Built here on the worker.
    std::shared_ptr<const Asset> source=original;
    if(layer) {
        auto mixed=std::make_shared<Asset>(*original);
        mixed->bytes.reset();mixed->midiPunches={};mixed->lowPunches={};
        // v0.4.67 PUNCH 2 TUNE: Punch 2 is pitched on its own (same Punch Pitch
        // mode) BEFORE it is mixed in; the mixed punch then follows Punch Pitch
        // and the keys like any punch. 0 st leaves Punch 2 untouched.
        pt::Sample add=layerRaw;
        if(std::abs(punch2Pitch)>1e-9)add=pt::renderPunchPitch(add,punch2Pitch,pitchMode);
        mixed->sample=mixLayer(original->sample,add,1.0,1.0);
        source=mixed;
    }
    // v0.5.4 PUNCH FOLLOWS TAIL with the Punch layer and "only Punch 2": the attack
    // (Punch 1) is pitched by PUNCH PITCH only, the decay (Punch 2) by PUNCH 2 TUNE +
    // PUNCH PITCH + the key; then they are mixed. Used for the main punch and every
    // tail key; the D2-C#3 octave-down lane keeps pitching the whole punch.
    const bool splitFollow=layer && follow && decayOnly;
    pt::Sample attackBase;
    if(splitFollow)attackBase=pt::renderPunchPitch(original->sample,pitch,pitchMode);
    const auto stale=[&] {
        if(layerValue()!=layer || pitchDropSettings(0)!=drop)return true;
        {const auto now=layerSettings();
         if(std::abs(now.split-ls.split)>1e-9||std::abs(now.endMs-ls.endMs)>1e-9)return true;
         if(layer && (std::abs(now.transition-ls.transition)>1e-9||
                      std::abs(now.offset-ls.offset)>1e-9||
                      std::abs(punch2PitchValue()-punch2Pitch)>1e-9))return true;}
        if(followValue()!=follow || decayOnlyValue()!=decayOnly || !(harmonyValue()==harmony))return true;
        if(threadShouldExit() || std::abs(settings().root-root)>.0001 ||
           std::abs(params.getRawParameterValue("punchPitch")->load()-pitch)>.0001 ||
           punchPitchModeValue()!=mode)return true;
        {const juce::ScopedLock lock(requestLock);if(requests[0].pending)return true;}
        const juce::ScopedLock lock(assetLock);return assets[0]!=original;
    };
    const auto render=[&](double shift) {
        auto result=std::make_shared<Asset>();
        if(splitFollow) {   // shift = PUNCH PITCH + key; the attack keeps PUNCH PITCH alone
            const auto decay=pt::renderPunchPitch(layerRaw,punch2Pitch+shift,pitchMode);
            const double outScale=double(attackBase.left.size())/double((std::max)(size_t(1),original->sample.left.size()));
            const double addScale=double(decay.left.size())/double((std::max)(size_t(1),layerRaw.left.size()));
            result->sample=mixLayer(attackBase,decay,outScale,addScale);
        } else
        result->sample=pt::renderPunchPitch(source->sample,shift,pitchMode);
        if(drop.active())result->sample=pt::drop::render(result->sample,drop,440.*std::pow(2.,(root+shift-69.)/12.),0.,stale);
        result->punchTimeScale=double(result->sample.left.size())/double(source->sample.left.size());
        result->name=source->name;result->punchEnd=source->punchEnd;
        return result;
    };
    std::shared_ptr<Asset> next;
    try {
        // v0.4.65: the main punch, the 12 upper-lane punches and the 12 low-lane
        // punches are independent renders of the same immutable source, so they
        // run in parallel (bit-identical per slot). A stale check aborts the whole
        // set exactly as the sequential loops did.
        std::atomic<bool> abort{false};
        const auto abortIfStale=[&]{ if(abort.load())return true; if(stale()){abort.store(true);return true;} return false; };
        // v0.4.67: slots 1..37 = internal notes 15..51 (pitched with the tail;
        // only 40..51 unless PUNCH FOLLOWS TAIL), 38..49 = the low lane.
        constexpr size_t tailSlots=size_t(pt::kPitchNoteCount);
        std::array<std::shared_ptr<Asset>,1+tailSlots+12> rendered{};
        pt::parallel::forEach(rendered.size(),[&](size_t i) {
            if(abortIfStale())return;
            if(i==0){rendered[0]=render(pitch);return;}
            if(i<=tailSlots) {
                const int note=pt::kLowestPitchNote+int(i)-1;
                if(pt::followsPunchMidi(note,follow))rendered[i]=render(pt::punchPitchForNote(note,root,pitch,follow)+harmony.interval(note));
                return;
            }
            // Low punch lane (keys D2..C#3): always Resample, one octave below the
            // tail heard on that key. Prepared here on the worker, never at note-on.
            const int key=pt::kLowPunchFirstKey+int(i-1-tailSlots);
            auto low=std::make_shared<Asset>();
            const double lowShift=pt::lowLanePunchPitch(key,root,pitch)+harmony.interval(key);   // v0.5.10: + harmony interval
            low->sample=pt::renderPunchPitch(source->sample,lowShift,pt::PunchPitchMode::Resample);
            if(drop.active())low->sample=pt::drop::render(low->sample,drop,440.*std::pow(2.,(root+lowShift-69.)/12.),0.,abortIfStale);
            low->punchTimeScale=double(low->sample.left.size())/double(source->sample.left.size());
            low->name=source->name;low->punchEnd=source->punchEnd;
            rendered[i]=std::move(low);
        });
        if(abort.load() || stale())return;
        next=std::move(rendered[0]);
        if(!next)return;
        for(size_t i=1;i<=tailSlots;++i)next->midiPunches[i-1]=std::move(rendered[i]);
        for(size_t i=0;i<12;++i)next->lowPunches[i]=std::move(rendered[1+tailSlots+i]);
    } catch(const std::exception& e) {if(stale())return;setStatus("Punch pitch failed: "+juce::String(e.what()));return;}
    if(stale())return;
    // v0.5.5: decay note of the main punch (root key): after ATTACK END, before the Punch End trim.
    try {
        const double scale=next->punchTimeScale>0?next->punchTimeScale:1.0;
        const double audible=(std::max)(0.0,next->sample.duration()-(std::max)(0.0,ls.endMs)*.001*scale);
        next->decayNote=pt::decaynote::analyse(next->sample,std::clamp(ls.split,0.0,1.0)*audible,audible);
    } catch(...) { next->decayNote={}; }
    if(stale())return;
    const juce::ScopedLock lock(assetLock);
    if(assets[0]!=original)return;
    if(preparedPunch)retiredAssets.push_back(preparedPunch);
    preparedPunch=std::move(next);preparedPunchSource=original;preparedPunchLayer=layer;preparedPunchPitch=pitch;
    preparedLayerSplit=ls.split;preparedLayerTransition=ls.transition;preparedLayerOffset=ls.offset;preparedLayerEnd=ls.endMs;
    preparedPunchRoot=root;preparedPunchMode=mode;preparedPunchDrop=drop;
    preparedPunchFollow=follow;preparedPunch2Pitch=punch2Pitch;preparedPunchDecayOnly=decayOnly;preparedPunchHarmony=harmony;
}
