void PunchTailProcessor::run() {
    pt::parallel::lowerCurrentThreadPriority();   // v0.5.10: the host's audio/UI threads win over preparation
    pt::TailCompositeCache compositeCache;
    bool backgroundPending=false;
    std::shared_ptr<const Asset> compositeCacheSource;
    while(!threadShouldExit()) {
      // v0.4.55: nothing may escape the preparation worker. An exception leaving
      // a JUCE thread terminates the whole host (FL Studio), so any unexpected
      // failure becomes a status message and the worker keeps running. The
      // previously published banks stay audible; the next pass retries.
      try {
        rebuildLinearEQ();
        rebuildBassMonoKernel();   // v0.5.1
        for(int slot=0;slot<4;++slot) {
            Request req;
            { const juce::ScopedLock l(requestLock);
                if(!requests[size_t(slot)].pending) continue;
                req=std::move(requests[size_t(slot)]);
                requests[size_t(slot)]={};
                // Publish the loading label before releasing requestLock so an
                // Unload action cannot be overwritten by stale decode progress.
                setStatus("Reading "+(req.fromState?req.name:req.file.getFileName())+"...");
            }
            if(slot==1){progress.setReady(0,pt::kPitchNoteCount);progress.setPhase(pt::progress::Phase::Setup);}   // v0.5.19 a new tail starts at 0
            // v0.5.16: decoding and analysis share the host-wide preparation slots.
            if(!claimPreparation(true,[&]{return threadShouldExit();}))break;
            juce::MemoryBlock bytes=std::move(req.bytes); juce::String error;
            if(!req.fromState && (req.file.getSize()>64*1024*1024 || !req.file.loadFileAsData(bytes))) {
                const juce::ScopedLock l(requestLock);
                if(req.generation==requestGenerations[size_t(slot)])
                    setStatus("Cannot read this file (maximum file size 64 MB).");
                continue;
            }
            auto loaded=decode(bytes,req.fromState?req.name:req.file.getFileName(),error,slot==1);
            if(!loaded) {
                const juce::ScopedLock l(requestLock);
                if(req.generation==requestGenerations[size_t(slot)]) setStatus(error);
                continue;
            }
            // Original bytes are never overwritten. Saved frame bounds are reapplied
            // after decode, before worker pitch/detection preparation.
            const int fullCount=int(loaded->sample.left.size());
            int first=std::clamp(req.trimFirst,0,fullCount);
            int last=req.trimLast<0?fullCount:std::clamp(req.trimLast,first,fullCount);
            if(first>=last){first=0;last=fullCount;}
            pt::cropSample(loaded->sample,size_t(first),size_t(last));
            bool silenceRemoved=false;
            if(req.trimSilence) {
                const auto bounds=pt::silenceBounds(loaded->sample);
                if(bounds.valid) {
                    silenceRemoved=bounds.begin>0 || bounds.end<loaded->sample.left.size();
                    last=first+int(bounds.end);first+=int(bounds.begin);
                    pt::cropSample(loaded->sample,bounds.begin,bounds.end);
                }
            }
            loaded->trimFirst=first;loaded->trimLast=last;
            if(slot==1 && (first!=0 || last!=fullCount))loaded->pitch=pt::refinedTailPitch(loaded->sample);
            if(slot==0) loaded->punchEnd=pt::detectPunchEnd(loaded->sample);
            const juce::ScopedLock requestGuard(requestLock);
            if(req.generation!=requestGenerations[size_t(slot)]) continue;
            if(slot==1 && !req.fromState) applyPitch(loaded->pitch);
            if(req.trimSilence && silenceRemoved) {
                // Silence trimming replaces the working sample; reset the lane's
                // old manual trim so it cannot unexpectedly trim audible content.

                for(const char* id:slot==0?std::array<const char*,2>{"punchOffset","punchExtra"}:std::array<const char*,2>{"trim","tailExtra"}) {
                    auto* parameter=params.getParameter(id);
                    parameter->setValueNotifyingHost(parameter->convertTo0to1(0));
                }
            }
            // Publish an immediately playable dry note bank BEFORE starting
            // expensive pitch analysis. It is immutable after publication.
            std::shared_ptr<Bank> immediate;
            if(slot==1) {
                immediate=std::make_shared<Bank>();
                immediate->root=settings().root;
                pt::fillDryPitchBank(immediate->notes,loaded->sample);
            }
            { const juce::ScopedLock l(assetLock);
                if(assets[size_t(slot)]) retiredAssets.push_back(assets[size_t(slot)]);
                assets[size_t(slot)]=std::move(loaded);
                if(slot==0) {
                    if(preparedPunch)retiredAssets.push_back(preparedPunch);
                    preparedPunch.reset();preparedPunchSource.reset();
                }
                if(slot==1) {
                    if(bank) retiredBanks.push_back(bank);
                    bank=std::move(immediate);
                    if(tailWetBank)retiredTailWetBanks.push_back(tailWetBank);
                    tailWetBank.reset();
                }
            }
            setStatus(req.trimSilence?(silenceRemoved?"Silence trimmed. Original file unchanged; trimmed sample saved in project.":"No removable edge silence. Sample and manual offsets kept."):slot==0?"Punch loaded.":slot==1?"Tail loaded. Original tail is playable; preparing pitches...":slot==3?"Punch 2 loaded. It is layered into Punch while PUNCH LAYER is ticked.":"Reverb loaded. Starts at the punch end; trim its beginning using Reverb Offset.");
        }
        rebuildPunch();
        collectRetired();
        {auto tail=asset(1);
         if(compositeCacheSource.get()!=tail.get()){compositeCache={};compositeCacheSource=tail;}}
        backgroundDeferMs=0;
        backgroundPending=prepareTailBanks(compositeCache);   // v0.5.15 played keys first, then the rest
        rebuildPhaseMap();
        rebuildCrunch();
      } catch(const std::exception& e) {
        rebuilding=false;
        setStatus("Preparation error (Kicktone kept running): "+juce::String(e.what()));
      } catch(...) {
        rebuilding=false;
        setStatus("Preparation error (Kicktone kept running).");
      }
        prepSlot.release();   // v0.5.16: other instances may prepare between passes
        // v0.5.10: come back soon when a render waits for settings to settle; v0.5.15: background batches follow at once;
        // v0.5.16: deferred background keys check again when the idle delay may have passed (a played key notify()s sooner).
        {const bool gated=renderGated;renderGated=false;
         wait(gated?25:backgroundDeferMs>0?juce::jlimit(20,250,backgroundDeferMs):backgroundPending?1:100);}
    }
}
// ===========================================================================
// v0.5.15 PLAYED KEYS FIRST (user request: less CPU after loading / changing
// settings). The tail bank, the Root Render composite, the crunch layers and
// the phase map are prepared in BATCHES of notes and published together:
//   1. the keys played in this project (saved as "playedKeys") are rendered
//      first and published at once, so they sound right almost immediately;
//   2. the remaining pitched keys follow in small background batches, nearest
//      to the root first; a key played meanwhile jumps the queue (next batch).
// Every rendered note is the exact same call as before (bit-identical); only
// the order and the moments of publication differ. Notes not rendered yet
// keep the dry tail, as during preparation in every earlier version.
// The rendered notes of the played keys are also saved INSIDE the project
// (user request) and restored without rendering when their key matches.
