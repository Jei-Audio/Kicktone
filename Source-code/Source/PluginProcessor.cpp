// v0.5.16 RENDER KEY (replaces the version in the content keys): the notes
// saved in a project stay valid across updates unless the rendering changed.
//  - TAILTONE_RENDER_SOURCE_KEY: CMake's hash of every DSP header (Source/*.h
//    except UI/scheduling files, plus r8brain); any edit there changes it.
//  - kRenderFormat: BUMP IT whenever code in PluginProcessor.cpp/.h changes the
//    prepared dry notes, Root Render composites or their base notes (render
//    glue, stretch/trim/drop arguments, composite settings) or the saved layout.
// A build without the generated header (scripts/CrossBuild.py) keys by version.
constexpr uint64_t kRenderFormat=2;
uint64_t renderKey() {
    uint64_t h=1469598103934665603ull;
    const auto mix=[&](uint64_t v){for(int i=0;i<8;++i){h^=uint8_t(v>>(8*i));h*=1099511628211ull;}};
   #ifdef TAILTONE_RENDER_SOURCE_KEY
    mix(TAILTONE_RENDER_SOURCE_KEY);
   #else
    for(const char* c=JucePlugin_VersionString;*c;++c){h^=uint8_t(*c);h*=1099511628211ull;}
   #endif
    mix(kRenderFormat);
    return h;
}
// Background batch order: nearest to the root first (most likely to be played).
std::vector<int> byDistanceFrom(std::vector<int> notes,double root) {
    std::stable_sort(notes.begin(),notes.end(),[&](int a,int b){return std::abs(a-root)<std::abs(b-root);});
    return notes;
}
bool completeRange(const std::bitset<128>& real) {
    for(int n=pt::kLowestPitchNote;n<=pt::kHighestPitchNote;++n)if(!real[size_t(n)])return false;
    return true;
}
