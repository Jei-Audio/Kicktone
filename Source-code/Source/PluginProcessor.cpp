void PunchTailProcessor::unloadFile(int slot) {
    if(slot<0 || slot>3) return;
    const auto n=size_t(slot);
    // Match the worker's requestLock -> assetLock order. Invalidating the
    // generation also prevents an already-decoding file from reappearing after
    // it was cleared, even if the user immediately loads a replacement.
    {
        const juce::ScopedLock requestGuard(requestLock);
        ++requestGenerations[n];
        requests[n]={};
        const juce::ScopedLock assetGuard(assetLock);
        if(assets[n]) retiredAssets.push_back(assets[n]);
        assets[n].reset();
        if(slot==0) {
            if(preparedPunch)retiredAssets.push_back(preparedPunch);
            preparedPunch.reset();preparedPunchSource.reset();
        }
        if(slot==1) {
            if(bank) retiredBanks.push_back(bank);
            bank.reset();
            if(tailWetBank)retiredTailWetBanks.push_back(tailWetBank);
            tailWetBank.reset();
        }
        ++unloadEpochs[n];
    }
    setStatus(slot==0 ? "Punch unloaded." : slot==1 ? "Tail unloaded." : slot==3 ? "Punch 2 unloaded." : "Reverb unloaded.");
    notify();
}
std::shared_ptr<PunchTailProcessor::Asset> PunchTailProcessor::decode(const juce::MemoryBlock& bytes,const juce::String& name,juce::String& error,bool detectPitch) {
    juce::AudioFormatManager formats; formats.registerBasicFormats();
    auto stream=std::make_unique<juce::MemoryInputStream>(bytes,false);
    std::unique_ptr<juce::AudioFormatReader> reader(formats.createReaderFor(std::move(stream)));
    if(!reader) { error="Unsupported or damaged audio file. Please use WAV or MP3."; return {}; }
    if(reader->sampleRate<8000 || reader->sampleRate>192000 || reader->lengthInSamples<=0 || reader->lengthInSamples/reader->sampleRate>5.0) {
        error="Use a kick sample up to 5 seconds long (8-192 kHz)."; return {};
    }
    juce::AudioBuffer<float> audio(2,int(reader->lengthInSamples));
    if(!reader->read(&audio,0,audio.getNumSamples(),0,true,true)) { error="The audio file could not be decoded."; return {}; }
    auto a=std::make_shared<Asset>(); a->name=name; a->bytes=bytes;
    a->sample.rate=reader->sampleRate;
    a->sample.left.assign(audio.getReadPointer(0),audio.getReadPointer(0)+audio.getNumSamples());
    a->sample.right=reader->numChannels==1 ? a->sample.left : std::vector<float>(audio.getReadPointer(1),audio.getReadPointer(1)+audio.getNumSamples());
    for(auto* channel:{&a->sample.left,&a->sample.right}) for(auto& value:*channel) if(!std::isfinite(value)) value=0;
    // Limit the prepared bank's memory use while retaining up to 24 kHz bandwidth.
    if(a->sample.rate>48000) {
        pt::Sample down; down.rate=48000; const auto count=size_t(std::llround(a->sample.duration()*48000));
        down.left.resize(count); down.right.resize(count);
        for(size_t i=0;i<count;++i) { const double pos=i*a->sample.rate/48000; down.left[i]=a->sample.at(0,pos,a->sample.rate/48000); down.right[i]=a->sample.at(1,pos,a->sample.rate/48000); }
        a->sample=std::move(down);
    }
    if(detectPitch) a->pitch=pt::refinedTailPitch(a->sample); return a;
}
void PunchTailProcessor::applyPitch(const pt::Pitch& pitch) {
    if(!pitch.valid) return;
    const double rounded=std::clamp(std::round(pitch.midi),double(tailRootMin),double(tailRootMax));
    auto set=[&](const char* id,float v) { auto* p=params.getParameter(id); p->setValueNotifyingHost(p->convertTo0to1(v)); };
    set("root",float(rounded)); set("cents",0.0f);
}
