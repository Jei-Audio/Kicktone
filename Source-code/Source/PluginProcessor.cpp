void PunchTailProcessor::rebuildPhaseMap() {
    auto s=settings();
    const bool automatic=params.getRawParameterValue("phaseAuto")->load()>0.5f;
    std::shared_ptr<const Asset> punch;
    std::shared_ptr<const Bank> pitches;
    std::shared_ptr<const TailWetBank> composite;
    {
        const juce::ScopedLock lock(assetLock);
        punch=currentPunch();pitches=bank;
        if(tailWetBank && compositeUsable(tailWetBank.get(),pitches.get()))composite=tailWetBank;
        s.punchTimeScale=punch?punch->punchTimeScale:1.;
        if(pitches)s.trimMs*=pitches->stretch;
        if(phaseMap && phaseMap->automatic==automatic && phaseMap->composite==composite && phaseMap->matches(s,punch.get(),pitches.get()))return;
    }
    if(!punch || !pitches)return;
    if(!claimPreparation(!prepSlot.isHeld(),[&]{return threadShouldExit();}))return;   // v0.5.16 shared preparation slots
    auto next=phaseFor(phaseMap,punch,pitches,composite,[&]{return threadShouldExit();});   // v0.5.15: final notes only, reuse unchanged ones
    if(!next)return;
    // The key check blocks publication of obsolete background work, without
    // holding a lock during phase scans.
    auto latest=settings();latest.trimMs*=pitches->stretch;latest.punchTimeScale=punch->punchTimeScale;
    if((params.getRawParameterValue("phaseAuto")->load()>0.5f)!=automatic ||
       !next->matches(latest,punch.get(),pitches.get()))return;
    const juce::ScopedLock lock(assetLock);
    if(currentPunch().get()!=punch.get() || bank.get()!=pitches.get())return;
    if(composite && tailWetBank!=composite)return;
    if(phaseMap)retiredPhaseMaps.push_back(phaseMap);
    phaseMap=std::move(next);
}
