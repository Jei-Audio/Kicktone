void PunchTailProcessor::rebuildCrunch() {
    // Built for every engine while MIX > 0. v0.5.15: layers follow the final
    // notes of the (possibly partial) bank; prepareTailBanks() extends them
    // batch by batch, this rebuilds them when CHARACTER / LOW CUT / LOST ONLY change.
    if(params.getRawParameterValue("crunchMix")->load()<=0.f)return;
    const int character=crunchCharacterValue();const double lowCut=crunchLowCutValue();const bool lostOnly=crunchLostOnlyValue();
    std::shared_ptr<const Bank> dry;std::shared_ptr<const TailWetBank> wet;std::shared_ptr<const CrunchBank> previous;
    {
        const juce::ScopedLock lock(assetLock);
        dry=bank;previous=crunchBank;
        if(tailWetBank && compositeUsable(tailWetBank.get(),dry.get()))wet=tailWetBank;
        if(!dry || !dry->usable() || rebuilding)return;
        if(crunchBank && crunchBank->dry==dry && crunchBank->wet==wet && crunchBank->character==character &&
           std::abs(crunchBank->lowCutHz-lowCut)<.5 && crunchBank->lostOnly==lostOnly)return;
        {KeyHash k;k.add(character).add(lowCut).add(lostOnly);   // v0.5.10: wait until CHARACTER / LOW CUT settle
         if(!crunchGate.ready(k.h)){renderGated=true;return;}}
    }
    const auto stale=[&] {
        if(threadShouldExit() || crunchCharacterValue()!=character || std::abs(crunchLowCutValue()-lowCut)>.5 || crunchLostOnlyValue()!=lostOnly)return true;
        const juce::ScopedLock lock(assetLock);
        return bank!=dry || (wet && tailWetBank!=wet);
    };
    // v0.5.16: a slot already held this pass (a background batch) keeps its kind.
    if(!claimPreparation(!prepSlot.isHeld(),stale))return;
    const ActivityScope activity(progress,pt::progress::Activity::Crunch);   // v0.5.19 progress bar
    bool aborted=false;
    auto next=crunchFor(previous,dry,wet,stale,aborted,true);
    if(!next || aborted || stale())return;
    const juce::ScopedLock lock(assetLock);
    if(crunchBank)retiredCrunch.push_back(crunchBank);
    crunchBank=std::move(next);
    setStatus("Crunch ready.");
}
